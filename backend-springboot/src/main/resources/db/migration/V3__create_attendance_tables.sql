CREATE TABLE classes (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR2(100) NOT NULL
);

CREATE TABLE matieres (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom VARCHAR2(150) NOT NULL,
    total_seances NUMBER(10) NOT NULL DEFAULT 15
);

CREATE TABLE seances (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_seance TIMESTAMP NOT NULL,
    classe_id NUMBER(19) NOT NULL,
    matiere_id NUMBER(19) NOT NULL,
    enseignant_id NUMBER(19) NOT NULL,
    CONSTRAINT fk_seances_classe FOREIGN KEY (classe_id) REFERENCES classes(id),
    CONSTRAINT fk_seances_matiere FOREIGN KEY (matiere_id) REFERENCES matieres(id),
    CONSTRAINT fk_seances_enseignant FOREIGN KEY (enseignant_id) REFERENCES users(id)
);

CREATE TABLE presences (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seance_id NUMBER(19) NOT NULL,
    etudiant_id NUMBER(19) NOT NULL,
    statut VARCHAR2(20) NOT NULL, -- PRESENT, ABSENT, JUSTIFIE
    CONSTRAINT uk_seance_etudiant UNIQUE (seance_id, etudiant_id),
    CONSTRAINT fk_presences_seance FOREIGN KEY (seance_id) REFERENCES seances(id),
    CONSTRAINT fk_presences_etudiant FOREIGN KEY (etudiant_id) REFERENCES users(id)
);

CREATE TABLE notifications (
    id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id NUMBER(19) NOT NULL,
    titre VARCHAR2(150) NOT NULL,
    message CLOB NOT NULL,
    lu NUMBER(1) NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES users(id)
);